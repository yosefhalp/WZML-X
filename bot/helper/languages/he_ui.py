def translate_button(label):
    """מתרגם רק את התווית החזותית ומשאיר את נתוני הפעולה ללא שינוי."""

    if not isinstance(label, str):
        return label
    if label in BUTTONS:
        return BUTTONS[label]
    if label.startswith("Done (") and label.endswith(")"):
        return f"סיום ({label[6:]}"
    if label.endswith(" User Token"):
        return f"{label[:-11]} טוקן משתמש"
    if label.endswith(" Recursive"):
        return f"{label[:-10]} חיפוש רקורסיבי"
    if label.startswith("Swap to ") and label.endswith(" Mode"):
        return f"מעבר למצב {label[8:-5]}"
    if label.startswith("Swap to ") and label.endswith(" token/config"):
        return f"מעבר לטוקן או להגדרה של {label[8:-13]}"
    if label.startswith("Swap to ") and label.endswith("'s Cookie File"):
        return f"מעבר לקובץ Cookies של {label[8:-14]}"
    if label.startswith("Auto-Create Folder "):
        return f"יצירת תיקייה אוטומטית {label[19:]}"
    if label.startswith("Drive Categories: "):
        return f"קטגוריות Drive: {label[18:]}"
    if label.startswith("Select: "):
        return f"בחירה: {label[8:]}"
    if label.startswith("Join "):
        return f"הצטרפות אל {label[5:]}"
    return label



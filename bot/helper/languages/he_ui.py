def translate_message(text):
    """מתרגם הודעות ישנות באופן מרוכז בלי לשנות פקודות, מזהים או כתובות."""

    if not isinstance(text, str):
        return text
    if text in MESSAGES:
        return MESSAGES[text]
    translated = text
    for source, target in sorted(PHRASES.items(), key=lambda item: len(item[0]), reverse=True):
        translated = translated.replace(source, target)
    return translated


def prepare_message(text):
    """מתרגם ועוטף כל מסך ישן בכיוון עברי בסיסי.

    מסכים חדשים יכולים לספק מעטפת דו־כיוונית מדויקת בעצמם. למסכים ישנים
    הפונקציה מבטיחה לפחות הקשר RTL עקבי, ומבודדת תוכן של ``code`` ו-``pre``
    משמאל לימין. כך נתיבים, פקודות ומזהים אינם מתהפכים בזמן שהסריקה
    ההדרגתית מחליפה כל מסך ב-renderer ייעודי.
    """

    from re import DOTALL, IGNORECASE, sub

    if not isinstance(text, str):
        return text
    # הודעה שמתחילה בפקודת Telegram משמשת לעיתים גם כחוזה פנימי בין
    # האשף למנוע המשימות. עטיפת כל ההודעה ב-RLI/PDI משנה את הטוקן הראשון
    # והאחרון (למשל ``-b``) ולכן שוברת את מנתח הארגומנטים. פקודות נשמרות
    # בדיוק כפי שנבנו; הודעות הסבר רגילות ממשיכות לקבל מעטפת RTL.
    if text.lstrip().startswith("/"):
        return text
    translated = translate_message(text)
    if not translated:
        return translated
    rli, lri, pdi = "\u2067", "\u2066", "\u2069"
    if translated.startswith(rli) and translated.endswith(pdi):
        return translated

    def isolate_code(match):
        opening, content, closing = match.groups()
        if content.startswith(lri) and content.endswith(pdi):
            return match.group(0)
        return f"{opening}{lri}{content}{pdi}{closing}"

    translated = sub(
        r"(<(?:code|pre)(?:\s[^>]*)?>)(.*?)(</(?:code|pre)>)",
        isolate_code,
        translated,
        flags=IGNORECASE | DOTALL,
    )
    return f"{rli}{translated}{pdi}"


def install_query_translation():
    """מחיל את אותו תרגום גם על התראות קצרות של כפתורי Telegram."""

    from pyrogram.types import CallbackQuery

    if getattr(CallbackQuery.answer, "_hebrew_ui", False):
        return

    original_answer = CallbackQuery.answer

    async def translated_answer(self, text=None, *args, **kwargs):
        return await original_answer(
            self,
            prepare_message(text) if text is not None else text,
            *args,
            **kwargs,
        )

    translated_answer._hebrew_ui = True
    CallbackQuery.answer = translated_answer
